"""Preliminary energy-based distance after turtle mode starts."""

ROUTES = [
    dict(id='road', name='Дорога с твёрдым покрытием', wh_km=[120, 180]),
    dict(id='terrain', name='Пересечённая местность', wh_km=[180, 250]),
    dict(id='offroad', name='Тяжёлое бездорожье', wh_km=[250, 400]),
]

METHOD = ('Предварительный пробег после включения «черепахи»: энергия, выданная '
          'батареей в этом режиме, × 1000 / принятый расход в Вт·ч/км. '
          'Дорога с твёрдым покрытием — 120–180 Вт·ч/км; пересечённая местность — '
          '180–250 Вт·ч/км; тяжёлое бездорожье (грязь, песок, крутые подъёмы) — '
          '250–400 Вт·ч/км. Это допущения для той же массы квадроцикла, а не '
          'измеренный расход и не цикл WMTC. Расход относится ко всему квадроциклу '
          'и уже включает потери привода и вспомогательные потребители; повторно '
          'применять КПД не нужно. Для двух независимых блоков энергия суммируется. '
          'Остаточная энергия взята из выбранного сценария; отдельные дорожные '
          'режимы не моделируются. При недостатке тяги сложный участок может '
          'оказаться непроходимым. Неизмеренная энергия ниже границы кривых не включена.')


def ranges(simulation, branches=1):
    if not simulation or simulation['turtle_start_min'] is None:
        return None
    wh = simulation['turtle_output_kwh'] * branches * 1000
    return {route['id']: [wh / route['wh_km'][1], wh / route['wh_km'][0]]
            for route in ROUTES}
